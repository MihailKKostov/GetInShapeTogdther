export function searchGeneric(q: string): Food[] {
  const terms = q.toLowerCase().split(/\s+/).filter(Boolean);
  if (!terms.length) return [];
  return GENERIC_FOODS.filter((f) => terms.every((t) => f.name.toLowerCase().includes(t))).slice(0, 15);
}
